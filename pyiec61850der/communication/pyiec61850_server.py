def run_ied_server_mms(ied_config: IedConfig, disp_interval:float=None):
    """
    This function builds and starts the IEC 61850 MMS server.
    """
        
    iec61850_server_mms = IEC61850ServerMMS(ied_config.interface.path_scl, ied_config.interface.path_lookup)

    data_model = iec61850_server_mms.build_ied_data_model()
    iec61850_server_mms.export_scl_data_model()
    ied_server = iec61850_server_mms.create_ied_server()
    iec61850_server_mms.create_lookup_table()
    iec61850_server_mms.create_data_buffer_map()
    
    iec61850_server_mms.container_guid = ied_config.container.container_guid
    iec61850_server_mms.container_name = ied_config.container.container_name
    
    # export lookup table as a CSV file
    logger.info(f'Path for lookup CSV: {iec61850_server_mms.path_lookup}')
    if os.path.isfile(iec61850_server_mms.path_lookup):
        if ied_config.interface.is_force_overwrite:
            logger.info('Found existing lookup table with the same filename, just overwrite it for security reasons.')
            iec61850_server_mms.export_lookup_csv()
        else:
            # NOTE: not force overwriting the lookup table may cause data inconsistence, only for test purpose.
            # TODO: -> add a function, updateLookupCSV() (as readLookCSV is not working properly)
            # one only needs to iterate by mms_addr and update guid and other stuff.
            iec61850_server_mms.read_lookup_csv(ied_config.interface.read_lookup_columns)
            logger.info('Found existing lookup table with the same filename, do not overwrite.')
    
    else:
        logger.info('Lookup table does not exist, create it.')
        iec61850_server_mms.export_lookup_csv()

    iec61850_server_mms.get_active_do_in_lookup()
    
    # TODO: is it necessary to check existing guid list to avoid overwriting?
    iec61850_server_mms.create_guid_table()
    
    logger.info('Pass the container_guid also to each data_buffer')
    for i, data_buffer in iec61850_server_mms.data_buffers.items():
        data_buffer.container_guid = iec61850_server_mms.container_guid
        data_buffer.container_name = iec61850_server_mms.container_name
    
    iec61850.IedServer_start(iec61850_server_mms.ied_server.swig_obj, ied_config.ied.tcp_port)
    logger.info('The IED server has been started')

    return iec61850_server_mms


