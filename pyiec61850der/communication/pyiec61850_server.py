    def build_do_in_ln(self, ln_obj: Type['SwigPyObject'], ln_template:dict):
        """
        This method build the entire DO object based on the contents in the DO template dictionary. The current LN
        object in iec61850._swig_obj must be passed as an input argument to the parameter ln_obj.
        During the DO build process, unsupported DA will be removed in the _server_model object, this is done by
        returning the objectLNBuilt object and passing to self.data_model._server_model after calling it.
        """

        ln_model_mod = copy.deepcopy(ln_template)  # this dictionary will be modified analogously and returned
        do_dumps = []
        logger.info(f'Start build Data Objects in LN {ln_template["@id"]}, DO of unsupported cdc type will be dropped, '
                    'dropping a DO may cause data model inconsistency, please validate the data model afterwards!')
        for i, do_entry in enumerate(ln_template['DO']):
            # the DO type is always 2 or 3 char before the _ in @type
            func_handler_name = f'CDC_{do_entry["@type"].split("_")[0]}_create'
            if not hasattr(iec61850, func_handler_name):
                # logger.warning('cdc type {} not supported by libiec61850, dropping DO {} of type {} '
                #                'from LN Template {}'.format(typeDO, do_entry['@name'], do_entry['@type'], ln_template['@id']))
                do_dumps.append(i)
            else:
                func_handler = getattr(iec61850, func_handler_name)
                # TODO: when creating DO in LN, some cdc types (e.g. ASG, APC) have more than 3 parameters, check
                #  whether any exemption is required for those
                
                if func_handler_name[4:7] == 'ASG':
                    do_obj = func_handler(do_entry['@name'], iec61850.toModelNode(ln_obj), 0, False)
                elif func_handler_name[4:6] == 'MV':
                    do_obj = func_handler(do_entry['@name'], iec61850.toModelNode(ln_obj), 0, False)
                elif func_handler_name[4:7] == 'APC':
                    do_obj = func_handler(do_entry['@name'], iec61850.toModelNode(ln_obj), 0, 2, False)
                elif func_handler_name[6] == 'C':
                    do_obj = func_handler(do_entry['@name'], iec61850.toModelNode(ln_obj), 0, 1)
                else:
                    do_obj = func_handler(do_entry['@name'], iec61850.toModelNode(ln_obj), 0)

                # Now iteratively add the DA and SDA to the DO object
                do_template = [do_type for do_type in self.data_model.do_templates
                                  if do_type['@id'] == do_entry['@type']]

                if not do_template:
                    logger.info('Can not find the DO template dictionary, probaly manually created data model.')
                    logger.info('Search for DA can not proceed, skip this DO, not data buffer will be created.')
                else:
                    # first check if SDO exists
                    sdo_models = self.get_items_from_dict(do_template[0], 'SDO')
                    if sdo_models:
                        for sdo_entry in sdo_models:
                            # attention, returned objectSDO is not of type sDataObject, but sModelNode, so objectSDO will never be used.
                            sdo_obj = iec61850.ModelNode_getChild(iec61850.toModelNode(do_obj), sdo_entry['@name'])
                            sdo_template = [do_type for do_type in self.data_model.do_templates
                                               if do_type['@id'] == sdo_entry['@type']]
                            if not sdo_template:
                                logger.info('Can not find the DA template dictionary, probaly manually created data model.')
                                logger.info('Search for SDA can not proceed, skip this SDO, not data buffer will be created.')
                            else:
                                # add a DataBuffer instance for each SDO
                                # Attention! Only the DO objects have SDO children, DA can only be accessed through DO objects, not SDO!
                                data_buffer = self.create_data_buffer(do_obj, do_entry, sdo_entry)
                                da_models = self.get_items_from_dict(sdo_template[0], 'DA')
                                self.update_data_buffer(data_buffer, do_obj, da_models, sdo_entry)
                                
                                data_buffer.iec61850_do.select_primary_da()
                                self.add_data_buffer_info(data_buffer)
                    else:            
                        # add a DataBuffer instance for this DO
                        data_buffer = self.create_data_buffer(do_obj, do_entry)
                        da_models = self.get_items_from_dict(do_template[0], 'DA')
                        self.update_data_buffer(data_buffer, do_obj, da_models)
    
                        data_buffer.iec61850_do.select_primary_da()
                        self.add_data_buffer_info(data_buffer)

        if do_dumps:
            logger.warning(f'Drop {len(do_dumps)} DO from the LN Template {ln_template["@id"]}')
            while do_dumps:
                idx = do_dumps.pop()
                logger.warning('Dropping DO {} of type {} from LN template {}.'.format(ln_template['DO'][idx]['@name'],
                                                                                       ln_template['DO'][idx]['@type'],
                                                                                       ln_template['@id']))
                del ln_model_mod['DO'][idx]  # dump the unsupported DO reversely

        return ln_model_mod

    def add_ds_to_ld(self, ld_model:dict):
        """
        This method takes the dictionary of one LD (ld_model) as input, extract the Data Sets contained in the
        Logical Nodes and add them to self.data_model._swig_obj.

        Because the DataSet in one LN can include DO from other LNs under the same parent LD, so the execution of this
        method must be performed after the entire LD build process has been finished. In other words, the function call
        should not be place within the method 'build_ld_obj', but rather in 'build_ied_data_model' after
        build_ld_obj has been called.

        It follows this approach:
            1. iteration over all DS in all LN in the LD
            2. for each of the fcda (functionally constrained data attribute) in every DS, localise the associated
                LN that has the same lnClass, lnInst and prefix by combining them in a tuple
            3. get the lnType of that DS, then find the associated LN template in self.data_model.ln_templates_buffer.
            4. check whether the fcda name is still in the DO list of that LN template
            5. If the DO is in the list, create the DataSet fcda entry, otherwise dump it from the DS

        Note:
             - the Data Sets could contain DO of unsupported cdc type, here they should also be removed from the
                data model.
             - an important assumption is that the DS of one certain LD will not include parameters in other LDs
        """

        if not self.data_model.ln_templates_buffer:
            raise ValueError('The LN Templates have not been validated by the method build_do_in_ln()!')

        ld_model_mod = copy.deepcopy(ld_model)

        # Step 1: iterate all DataSets in all LN in the LD
        ln_models = copy.deepcopy(ld_model['LN'])
        ln_models.append(ld_model['LN0'])
        # create a list of all LN identifiers in the LD
        ln_identifiers = [self.get_ln_id('LD', v) for i, v in enumerate(ln_models)]

        for i, ln_model in enumerate(ln_models):
            _ln_name = self.get_ln_name(ln_model)
            log_msg = f'The LN {_ln_name} has no DataSet'
            ds_models = self.get_items_from_dict(ln_model, 'DataSet', log_msg, 'info')
            if i == len(ln_models)-1:  # the last element implies LLN0, which should have the index -1
                _ln_idx = -1
                is_lln0 = True
            else:
                _ln_idx = i
                is_lln0 = False

            # get parent LN object that owns the data set
            target_key = (self.ied_server.current_ld_obj_id, _ln_idx)
            parent_ln_obj = self.ied_server.ln_objs.get(target_key)

            if not parent_ln_obj:
                # Handle the case where the LN doesn't exist
                logger.error(f"LN with ID {target_key} not found.")
                logger.error(f"The resulting data model may have inconsistency regarding data set {target_key}.")

            ds_dumps = []  # prepare a list for to be dumped dataSets (empty DataSets)
            for j, ds_model in enumerate(ds_models):
                ds_name = ds_model['@name']
                log_msg = f'The DataSet {ds_name} has no fcda element, check the data model again!'
                fcda_models = self.get_items_from_dict(ds_model, 'FCDA', log_msg, 'warning')

                # Step 2.1: for each fcda in each DS, get the id of target LN
                fcda_dumps = []
                for k, fcda_model in enumerate(fcda_models):
                    fcda_name = fcda_model['@doName']
                    parent_ln_id_str = self.get_ln_id('DS', fcda_model)
                    # Step 2.2: localise the associated LN by indexing the id
                    parent_ln_id_idx = [idx for idx, val in enumerate(ln_identifiers) if val == parent_ln_id_str]
                    # Step 3: determine the LNType of associated LN using the id index
                    if not parent_ln_id_idx:
                        logger.error(f'Identifier search implies no match, there is something wrong with the '
                                     f'data model, double check if the entry {fcda_name} in DataSet {ds_name} '
                                     f'is valid')
                        logger.warning(f'One DataSet entry {fcda_name} in {parent_ln_id_str} can not be created, '
                                       f'double check the data model. Incorrect DataSet entry may result data model '
                                       f'inconsistency on the client side!')
                        continue
                    elif parent_ln_id_idx[0]==len(ln_identifiers)-1:  # this implies the associated LN is LLN0
                        parent_ln_type = ld_model['LN0']['@lnType']
                    else:
                        parent_ln_type = ld_model['LN'][parent_ln_id_idx[0]]['@lnType']
                    # Step 4: check if the DO is still contained in the LN Template
                    # since the LN template has unique id, we expect either an empty list or a list with one element
                    valid_ln_types = [(idx,val) for idx,val in
                                    enumerate(self.data_model.ln_templates_buffer) if val['@id'] == parent_ln_type]
                    if not valid_ln_types:
                        logger.error(f'The target LN template {parent_ln_type} not found, double check the data model!')
                    else:
                        (parent_ln_idx, parent_ln_models) = valid_ln_types[0]

                        # Step 5.1: add the DataSet fcda entry to dump list
                        valid_do_names = [do_entry['@name'] for do_entry in parent_ln_models['DO']]
                        if fcda_name not in valid_do_names:
                            logger.info(f'Can not find DO {fcda_name} in the LN Template after build, dump fcda in DS')
                            fcda_dumps.append(k)

                # Step 5.2: dump the DataSet fcda entry
                if len(fcda_dumps) == len(fcda_models):  # this implies all fcda must be dumped -> del the DS
                    ds_dumps.append(j)
                    continue
                elif not fcda_dumps:
                    #pass
                    #listDictFCDAUpdated = dictLDBuiltUpdated['LN'][idxLNInLD]['DataSet'][idxDSInLN]['fcda']
                    fcda_models_mod = copy.deepcopy(fcda_models)  # nothing to dump, move forward
                else:
                    # listDictFCDAUpdated = listDictFCDA
                    if is_lln0:
                        while fcda_dumps != []:
                            fcda_dump_idx = fcda_dumps.pop()
                            fcda_dump_name = ld_model_mod['LN0']['DataSet'][j]['FCDA'][fcda_dump_idx]['@doName']
                            logger.warning(f'fcda with reference {fcda_dump_name} is dumped in the DataSet {ds_name}.')
                            del ld_model_mod['LN0']['DataSet'][j]['FCDA'][fcda_dump_idx]
                        fcda_models_mod = copy.deepcopy(ld_model_mod['LN0']['DataSet'][j]['FCDA'])
                    else:
                        while fcda_dumps != []:
                            fcda_dump_idx = fcda_dumps.pop()
                            del ld_model_mod['LN'][i]['DataSet'][j]['FCDA'][fcda_dump_idx]  # remove the fcda in the
                            # data model dict
                        fcda_models_mod = copy.deepcopy(ld_model_mod['LN'][i]['DataSet'][j]['fcda'])

                # Now create the DataSet object
                logger.info(f'Create DS object for the DataSet named {ds_name}, {len(fcda_models_mod)} fcda entries in this DS')
                ds_obj = iec61850.DataSet_create(ds_name, parent_ln_obj)  # create DataSet in server data model
                
                # Attention, the LN name is not nameThisLN, but the name of the LN that contains the DO!!
                    # Assume all DS are in the LD that the LN belongs to
                    # official note in libiec61850:
                    #   Note: Be aware that data set entries are not IEC 61850 object reference but MMS variable names that have to contain the LN
                    #   name, the fc and subsequent path elements separated by "$" instead of ".". This is due to efficiency reasons
                    #   to avoid the creation of additional strings. If the variable parameter does not contain a logical device name (separated from the 
                    #   remaining variable name by the "/" character) the logical device where the data set resides is used automatically.
                
                for fcda_model in fcda_models_mod:
                    if fcda_model['@lnClass'] == 'LLN0':
                        ds_entry_str = '{}${}${}'.format(fcda_model['@lnClass'], fcda_model['@fc'], fcda_model['@doName'])
                    else:
                        ds_entry_str = '{}{}{}${}${}'.format(fcda_model['@prefix'], fcda_model['@lnClass'], fcda_model['@lnInst'],
                                                           fcda_model['@fc'], fcda_model['@doName'])
                    
                    fcda_obj = iec61850.DataSetEntry_create(ds_obj, ds_entry_str, -1, None)

            # Now dump empty DataSets
            if ds_dumps:
                logger.warning(f'Inconsistent DS detected, {len(ds_dumps)} DataSet must be dumped in the LN {_ln_name}')
            while ds_dumps != []:
                ds_dump_idx = ds_dumps.pop()
                if is_lln0:
                    ds_dump_name = ld_model_mod['LN0']['DataSet'][ds_dump_idx]['@name']
                    logger.warning(f'DS with reference {ds_dump_name} is dumped.')
                    del ld_model_mod['LN0']['DataSet'][ds_dump_idx]
                else:
                    ds_dump_name = ld_model_mod['LN'][i]['DataSet'][ds_dump_idx]['@name']
                    logger.warning(f'DS with reference {ds_dump_name} is dumped.')
                    del ld_model_mod['LN'][i]['DataSet'][ds_dump_idx]
        return ld_model_mod

    def add_rcb_to_ld(self, ld_models:dict|None=None):
        """
        This method takes the dictionary of one LD (ld_model) as input, extract the Report Control Blocks
        contained in the Logical Nodes and accordingly add them to self.data_model._swig_obj. Normally, the
        reports will be linked to DS that is (are) contained in the same Logical Node, well to make the entire module
        compatible for other IEC 61850 data model, this method will still scan all Logical Nodes in one LD and check
        whether the DS reference is valid.

        TODO: add log messages for this method

        Note:
            - Regarding the report configuration on the server side, this method will not change anything, it just
                takes over the original configuration as they are in the data model.
            - Theoretically, we can always search for the corresponding reports as long as one DataSet has been created,
                well this will require a second-level iteration of RCB search over all LN within the first-level loop,
                which is surely an error source. To avoid problems associated with this, this method is added to the
                module. Basically it triggers another first-level loop search after the DS build process is finished.
            - This method has some duplicate codes in add_ds_to_ld, well I won't make the effort to improve this.
        """

        ld_models_mod = copy.deepcopy(ld_models)

        # Step 1: iterate all DataSets in all LN in the LD
        ln_models = copy.deepcopy(ld_models['LN'])
        ln_models.append(ld_models['LN0'])
        # create a list of all LN identifiers in the LD
        ln_identifiers = [self.get_ln_id('LD', ln_model) for idx, ln_model in enumerate(ln_models)]

        for i, ln_model in enumerate(ln_models):
            _ln_name = self.get_ln_name(ln_model)
            if i == len(ln_models) - 1:  # the last element implies LLN0, which should have the index -1
                _ln_idx = -1
                is_lln0 = True
            else:
                _ln_idx = i
                is_lln0 = False
            target_key = (self.ied_server.current_ld_obj_id, _ln_idx)
            parent_ln_obj = self.ied_server.ln_objs.get(target_key)
            log_str = f'The LN {_ln_name} has no Report Control Block'
            rcb_models = self.get_items_from_dict(ln_model, 'ReportControl', log_str, 'info')
            for j, rcb_model in enumerate(rcb_models):
                # first get basic info
                rcb_name = rcb_model['@name']
                rcb_id = rcb_model['@rptID']
                rcb_ref_ds = rcb_model['@datSet']
                rcb_integrity = int(rcb_model['@intgPd'])
                rcb_conf_rev = int(rcb_model['@confRev'])
                if '@buffered' in rcb_model:
                    is_buffered = rcb_model['@buffered']
                else:
                    is_buffered = False  # if not defined, a report is set to be unbuffered
                if '@bufTime' in rcb_model:
                    buffer_time = int(rcb_model['@bufTime'])  # TODO: add a type check here
                else:
                    buffer_time = 0  # if not defined, buffer time is set to 0

                # calculate bit mask for trigger options
                trigger_opt_models = rcb_model['TrgOps']
                trigger_opts = {'@dchg': 1, '@qchg': 2, '@dupd': 4, '@period': 8, '@gi': 16}
                flag_tri_opt = 0
                for key, val in trigger_opts.items():
                    flag_tri_opt = flag_tri_opt + val*bool(trigger_opt_models.get(key, False))

                # calculate bit mask for option fields
                opt_field_models = rcb_model['OptFields']
                opt_fields = {'@seqNum': 1, '@timeStamp': 2, '@reasonCode': 4, '@dataSet': 8, '@dataRef': 16,
                                '@BufOvfl': 32, '@entryID': 64, '@configRef': 128}
                flag_opt_field = 0
                for key, val in opt_fields.items():
                    flag_opt_field = flag_opt_field + val*bool(opt_field_models.get(key, False))

                # build Report Control Block objects
                rcb_obj = iec61850.ReportControlBlock_create(rcb_name, parent_ln_obj, rcb_id, is_buffered, rcb_ref_ds,
                                                   rcb_conf_rev, flag_tri_opt, flag_opt_field,
                                                   buffer_time, rcb_integrity)

        return ld_models_mod

    def create_ied_server(self) -> Type["SwigPyObject"] | None:
        """ Run the IED Server using the data model built by self.build_ied_data_model. """

        logger.info('Create the IED server using current version of the data model')
        assert self.data_model.swig_obj, 'No data model available, please build the data model first!'

        # NOTE: onc could consider add topology check before running the server.
        # Currently, we assume the data model is okay
        swig_obj = iec61850.IedServer_create(self.data_model.swig_obj)
        logger.info('The IED server has been created')

        self.ied_server.swig_obj = swig_obj
        DataBuffer.ied_server_swig_obj = swig_obj

        logger.info('The IED server swig object has been attached to the DataBuffer class')

        return swig_obj

    def destroy_ied_server(self):
        """Cleanly stop and destroy libiec61850 C objects."""

        swig_obj = getattr(self.ied_server, 'swig_obj', None) if hasattr(self, 'ied_server') else None

        if swig_obj is not None:
            try:
                # 1. Stop TCP server from accepting new connections / stop worker threads
                iec61850.IedServer_stop(swig_obj)

                # 2. Free C memory allocated for the IED server instance
                iec61850.IedServer_destroy(swig_obj)

                logger.info("IEC 61850 C-Server stopped and destroyed cleanly.")
            except Exception as e:
                logger.error(f"Failed to destroy C-Server object: {e}")
            finally:
                # Clear reference so repeated calls or checks evaluate to None
                self.ied_server.swig_obj = None
                DataBuffer.ied_server_swig_obj = None
        else:
            logger.warning("destroy_ied_server called, but no active C-Server object was found.")

    def dump_invalid_char(self, obj_level:str='LD', obj_str:str='dummy'):
        """
        This method helps to dump not allowed characters in the object name, it returns the updated name.
        obj_level could be LD, LN, DO.....
        """
        for i, char in enumerate(self.server_config.INVALID_CHARS):
            if char in obj_str:
                obj_str = obj_str.strip(char)
                logger.warning(f'The {obj_level} name {obj_str} contains banned character'
                               f' {char}, automatically removed')
        return obj_str

    @staticmethod
    def get_items_from_dict(dict_obj:dict, key:str, log_str:str|None=None, log_level:str= 'info') -> list:
        """
        This method checks if an item (which should be a list) with given key exists and returns the list of it.

        If the list contains only a single element of the list, its type will be OrderedDict.

        The third argument could be a log message if the item does not exist, with given log_level. Log level are the
        standard levels of built-in function logging (info, error, warning, ...)
        """

        vals = []
        if key not in dict_obj:
            if log_str is not None:
                log_func = getattr(logger, log_level)
                log_func(log_str)
        elif isinstance(dict_obj[key], dict):  # this implies a single fcda, OrderedDict is also dict
            vals = [dict_obj[key]]
        elif isinstance(dict_obj[key], list):
            vals = dict_obj[key]
        # leave out the else here to catch runtime errors
        return vals

    @staticmethod
    def get_ln_name(ln_model:dict) -> str:
        """ This method takes the dictionary object of a LN and build the LN name string. """
        if ln_model['@lnClass'] == 'LLN0':
            return f'{ln_model["@lnClass"]}{ln_model["@inst"]}' # although the inst should be ''
        else:
            return f'{ln_model["@prefix"]}{ln_model["@lnClass"]}{ln_model["@inst"]}'

    @staticmethod
    def get_ln_id(level:str, ln_model:dict) -> tuple:
        """
        This method creates an id for one Logical Node dictionary taken from the SCL data model, which is either
        a 'fcda' dict from a DataSet, or an element of the 'LN0' or 'LN' list in the dict 'LDevice'. This method will be
        called when searching for the LN that contains the DO in a DataSet.

        Input parameter:
            - level: either 'DS' or 'LD', unknown level will cause returning a tuple with an empty string
            - ln_model: the dict object that contains the id information
        output parameter:
            - identifierLN: the id of the LN
        """

        if level == 'DS':
            if ln_model['@lnClass'] == 'LLN0':  # LLN0 is a exemption, it has no prefix and lnInst
                ln_id = (ln_model['@lnClass'],)
            else:
                ln_id = (ln_model['@lnClass'], ln_model['@lnInst'], ln_model['@prefix'])
        elif level == 'LD':
            if ln_model['@lnClass'] == 'LLN0':  # LLN0 is an exemption, it has no prefix and lnInst
                ln_id = (ln_model['@lnClass'],)
            else:
                ln_id = (ln_model['@lnClass'], ln_model['@inst'], ln_model['@prefix'])
        else:
            ln_id = ('',)

        return ln_id

    @staticmethod
    def get_iec61850_tstmp(tstmp_unix:float):
        """ This method will convert a Unix timestamp (float) into the format that the IEC 61850 compliant
         IED Server can understand, more specifically, it converts the seconds to milliseconds"""

        iec61850_tstmp = None
        SCALE_FACTOR = 1000
        if not isinstance(tstmp_unix, (float, np.float64, np.float32, np.floating)):
            logger.warning('Wrong data type, input timestamp must be a Unix float value')
        else:
            iec61850_tstmp = tstmp_unix * SCALE_FACTOR

        return iec61850_tstmp

