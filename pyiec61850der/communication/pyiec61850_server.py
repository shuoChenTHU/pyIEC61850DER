    def build_ied_data_model(self):
        """
        Build the IED data model according to the topology of the input SCL file.
        """

        logger.info('Start the build process of a new IEC 61850 data model.')
        if self.data_model.swig_obj is not None:
            # TODO: consider how to preserve the data model reversion
            logger.warning('There exists already a data model, the build process will overwrite it.')
            self.data_model.archives.append(self.data_model.swig_obj)

        self.data_model.swig_obj = iec61850.IedModel_create(self.data_model.ied_name)
        logger.info(f'Date model with the IED name {self.data_model.ied_name} has been generated')

        # Now iteratively build LD
        ld_models = self.data_model.server_model_orig['LDevice']
        if type(ld_models) is not list:
            ld_models = [ld_models]
        for i, ld in enumerate(ld_models):
            self.ied_server.current_ln_obj_id = 0
            # NOTE: currently only modified ld_model is saved, it is assumed that no interim information is helpful.
            ld_model = self.build_ld_obj(ld)
            ld_model = self.add_ds_to_ld(ld_model)
            ld_model = self.add_rcb_to_ld(ld_model)

            if len(ld_models) == 1:
                self.data_model.server_model['LDevice'] = ld_model
            else:
                self.data_model.server_model['LDevice'][i] = ld_model
                self.ied_server.current_ld_obj_id += 1
        logger.info('Data model build process finished')
        return self.data_model

    def build_ld_obj(self, ld_model:dict) -> dict:
        """
        This method builds an object that contains the child objects of one Logical Device.
        Before creating the LD objects, the data model object must have been initialized and stored
        in self._swig_obj.

        In the SCL file, the one-liner LN/DO/DA looks like this:
        <LN desc="Default MMXU template" inst="1" lnType="MMXU_0" lnClass="MMXU" prefix=""></LN>
        <DO desc="" type="MV_0" name="TotW"></DO>
        <DA bType="Struct" fc="MX" name="mag" dchg="true" dupd="true" type="AnalogueValue_0"></DA>
        <EnumVal ord="1">Single phase to neutral</EnumVal>

        TODO: modularise this function!
        NOTE:
            - the LD name shall not contain the special character '_', if so, it will automatically be removed
            - only the dict ld_model_mod will be modified analogously and returned
            - LLN0 must be handled differently as other LN
        """

        ld_model_mod = copy.deepcopy(ld_model)
        # dump not allowed special characters in LD name and create the LD object
        ld_name_orig = ld_model['@inst']
        logger.info(f'Checking LD name of {ld_name_orig}')
        ld_name = self.dump_invalid_char('LD', ld_name_orig)
        ld_model_mod['@inst'] = ld_name
        self.ied_server.current_ld_name = ld_name

        logger.info(f'Create Logical Device {ld_name} in the IED server')
        ld_obj: Type['SwigPyObject'] = iec61850.LogicalDevice_create(ld_name, self.data_model.swig_obj)
        self.ied_server.ld_obj_ids.add(self.ied_server.current_ld_obj_id)
        self.ied_server.ld_objs.update({self.ied_server.current_ld_obj_id:ld_obj})
        self.ied_server.current_ld_obj = ld_obj

        # start building the Logical Node
        logger.info(f'Start the build process for the LD {ld_name}')

        # first build LLN0
        if 'LN0' not in ld_model:
            logger.warning('Logical Node LLN0 not found, the builder moves forward, please check the data model later')
        else:
            ld_model_mod['LN0']['@lnClass'] = self.dump_invalid_char('LN0', ld_model['LN0']['@lnClass'])
            ln0_name = self.get_ln_name(ld_model['LN0'])
            self.ied_server.current_ln_name = ln0_name
            ln0_type = ld_model['LN0']['@lnType']
            ln0_obj: Type['SwigPyObject'] = iec61850.LogicalNode_create(ln0_name, ld_obj)

            # record the iec61850 object references
            self.ied_server.current_ln_obj = ln0_obj
            # use the pair (ld_obj_id, ln_obj_id) as key of the ln_obj in the dict
            current_ln_id_pair = (self.ied_server.current_ld_obj_id, -1,)
            self.ied_server.ln_obj_ids.add(current_ln_id_pair)
            self.ied_server.ln_objs.update({current_ln_id_pair: ln0_obj})

            # Now dump unsupported DO in the LN templates
            index = next((i for i, ln in enumerate(self.data_model.ln_templates)
                          if ln['@id'] == ln0_type), None)
            if index is not None:
                self.data_model.ln_templates_buffer[index] = self.build_do_in_ln(ln0_obj, self.data_model.ln_templates[index])
            else:
                logging.error(f"LN type {ln0_type} not found in templates.")

        # then build all other LNs
        ln_models = ld_model['LN']
        if type(ln_models) is not list:
            ln_models = [ln_models]
        
        for i, ln_model in enumerate(ln_models):
            ld_model_mod['LN'][i]['@lnClass'] = self.dump_invalid_char('LN', ln_model['@lnClass'])
            ln_name = self.get_ln_name(ln_model)
            self.ied_server.current_ln_name = ln_name
            ln_type = ln_model['@lnType']
            ln_obj: Type['SwigPyObject'] = iec61850.LogicalNode_create(ln_name, ld_obj)

            # record the iec61850 object references
            self.ied_server.current_ln_obj = ln_obj
            # use the pair (ld_obj_id, ln_obj_id) as key of the ln_obj in the dict
            current_ln_id_pair = (self.ied_server.current_ld_obj_id, self.ied_server.current_ln_obj_id,)
            self.ied_server.ln_obj_ids.add(current_ln_id_pair)
            self.ied_server.ln_objs.update({current_ln_id_pair:ln_obj})
            self.ied_server.current_ln_obj_id += 1

            # Now dump unsupported DO in the LN templates
            index = next((i for i, ln in enumerate(self.data_model.ln_templates)
                          if ln['@id'] == ln_type), None)
            if index is not None:
                self.data_model.ln_templates_buffer[index] = self.build_do_in_ln(ln_obj, self.data_model.ln_templates[index])
            else:
                logging.error(f"LN type {ln_type} not found in templates.")

        return ld_model_mod
    
    
    def create_data_buffer(self, do_obj:Type["SwigPyObject"], do_entry:dict, sdo_entry: dict|None=None) -> DataBuffer:
        """
        This method automatically create a DataBuffer instance and add it to the attribute data_buffers.
        But the initially created instace contains only limited amount of information, many attributes require 
        update later after server initialization, e.g. first get config info / mapping table / lookup table and
        then update the attributes in the DataBuffer accordingly.
        
        To perform the tasks correctly, the call of this method must be placed in the middel of the method 
        self.build_do_in_ln.
        
        Since DO/SDO is the key of the DataBuffer instances, and the configuration of DO/SDO in the libiec61850 
        IED server is based on DO/SDO type templates, this method requires passing the associated
        refObject and entry to specify DO/SDO, DA and SDO related information.
        
        SDO objects have been considiered during the implementation, this was mainly due to the application of DEL and WYE
        for three phase systems.
        
        Inputs:
            - do_obj: the reference object of the associated DO (DA can not be accessed through SDO!)
            - do_entry: entry of the DO in the dictTemplateDO
            - sdo_entry: entry of the SDO in the dictTemplateDO, leave it None to represent the non-existence of SDO objects
        """
        
        data_buffer = DataBuffer()
        
        # first set its own attributes
        data_buffer.index = self.data_buffer_count
        self.data_buffer_count += 1
        data_buffer.data_source = 'disabled'  # default is disabled, to avoid unnecessary data volume
        
        if sdo_entry is not None:
            data_buffer.iec61850_do.level = 'SDO'
            mms_addr = f'{self.data_model.ied_name}_{self.ied_server.current_ld_name}/{self.ied_server.current_ln_name}.{do_entry["@name"]}.{sdo_entry["@name"]}'
            comm_addr = f'{self.data_model.ied_name}${self.ied_server.current_ld_name}${self.ied_server.current_ln_name}${do_entry["@name"]}${sdo_entry["@name"]}'
            data_buffer.iec61850_do.name = f'{do_entry["@name"]}.{sdo_entry["@name"]}'
            data_buffer.iec61850_do.type = sdo_entry['@type']
            data_buffer.iec61850_do.cdc = sdo_entry['@type'].split('_')[0]
        else:
            mms_addr = f'{self.data_model.ied_name}_{self.ied_server.current_ld_name}/{self.ied_server.current_ln_name}.{do_entry["@name"]}'
            comm_addr = f'{self.data_model.ied_name}${self.ied_server.current_ld_name}${self.ied_server.current_ln_name}${do_entry["@name"]}'
            data_buffer.iec61850_do.name = do_entry['@name']
            data_buffer.iec61850_do.type = do_entry['@type']
            data_buffer.iec61850_do.cdc = do_entry['@type'].split('_')[0]
        
        data_buffer.id = mms_addr  # currently use the IEC 61850 MMS address as id

        # This is only the guid data_buffer, the guid of container will be passed by other methods as data_buffer.container_guid
        # NOTE: if a lookup table exists, then the guid will be later updated from there!
        data_buffer.guid = str(uuid.uuid4())
        
        # IEC 61850 DO
        data_buffer.iec61850_do.id = mms_addr
        data_buffer.iec61850_do.mms_addr = mms_addr
        data_buffer.iec61850_do.comm_addr = comm_addr

        # FIXME: major refactoring once for all
        data_buffer.iec61850_do.obj_ref_map['ld'] = self.ied_server.current_ld_obj
        data_buffer.iec61850_do.obj_ref_map['ln'] = self.ied_server.current_ln_obj
        data_buffer.iec61850_do.obj_ref_map['do'] = do_obj
        
        self.add_data_buffer(data_buffer)
        
        return data_buffer

    @staticmethod
    def add_da_to_data_buffer(data_buffer_do: DataBuffer, da_entry:dict, da_obj: Type["SwigPyObject"],
                              bda_name:str|None=None) -> IEC61850DA:
        """
        This method can be used to create a instance of interface.runtime.IEC61850DA.
        It requires the initialization of a DataBuffer that contains DO information, this method only initialize
        DA instances for the data buffer and add them to the list.
        It should be called during the iterative creation of DA in the method self.build_do_in_ln.
        
        NOTE: currently we skip the level SDO, if a DO containing SDO is detected, the function in
                communication._swig_obj will search for the DA in those SDA and add them to the
                _da_objs
        NOTE: this method does not depend on self, but for now it is better to let it stay here.
        """
        
        iec61850_da = IEC61850DA()
        iec61850_da.level = 'DA'
        
        # first create the IEC61850DA instance
        mms_addr = f'{data_buffer_do.iec61850_do.mms_addr}.{da_entry["@name"]}'
        comm_addr = f'{data_buffer_do.iec61850_do.comm_addr}${da_entry["@name"]}'
        iec61850_da.name = da_entry['@name']

        
        if bda_name is not None:
            mms_addr = f'{mms_addr}.{bda_name}'
            comm_addr = f'{mms_addr}${bda_name}'
            iec61850_da.name = f'{iec61850_da.name}.{bda_name}'
            iec61850_da.level = 'BDA'
        
        iec61850_da.id = mms_addr
        iec61850_da.mms_addr = mms_addr
        iec61850_da.comm_addr = comm_addr
        iec61850_da.do_mms_addr = data_buffer_do.iec61850_do.mms_addr
        iec61850_da.do_comm_addr = data_buffer_do.iec61850_do.comm_addr
        if '@type' in da_entry:
            iec61850_da.type = da_entry['@type']
        iec61850_da.bType = da_entry['@bType']
        iec61850_da.fc = da_entry['@fc']
        iec61850_da.guid = str(uuid.uuid4())

        assert isinstance(data_buffer_do.iec61850_do.obj_ref_map, dict)
        iec61850_da.ld_obj_ref = data_buffer_do.iec61850_do.obj_ref_map['ld']
        iec61850_da.ln_obj_ref = data_buffer_do.iec61850_do.obj_ref_map['ln']
        iec61850_da.do_obj_ref = data_buffer_do.iec61850_do.obj_ref_map['do']
        iec61850_da.da_obj_ref = da_obj
        
        data_buffer_do.iec61850_do.add_iec61850_da(iec61850_da)
        
        return iec61850_da
        
    
